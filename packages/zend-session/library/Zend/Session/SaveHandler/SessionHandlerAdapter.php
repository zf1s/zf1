/**
 * Exposes a Zend_Session_SaveHandler_Interface implementation as a SessionHandlerInterface
 *
 * Used by Zend_Session::setSaveHandler() on php 8.4+, which deprecated passing the save handler
 * callbacks to session_set_save_handler() one by one. Calls and return values of the six save
 * handler methods are passed through unchanged.
 *
 * create_sid() and validateId() are required by php 8.6+ and reproduce what php does for save
 * handlers registered with callbacks, which have neither:
 * - session ids are generated by php's default generator
 * - any session id is considered valid, also with session.use_strict_mode enabled
 * - newly generated session ids are not checked for collisions
 * updateTimestamp() is not defined on purpose, php keeps calling write() instead.
 *
 * @category   Zend
 * @package    Zend_Session
 * @subpackage SaveHandler
 * @copyright  Copyright (c) 2005-2015 Zend Technologies USA Inc. (http://www.zend.com)
 * @license    http://framework.zend.com/license/new-bsd     New BSD License
 */
class Zend_Session_SaveHandler_SessionHandlerAdapter implements SessionHandlerInterface
{
    /**
     * @var Zend_Session_SaveHandler_Interface
     */
    protected $_saveHandler;

    /**
     * Session id generated by create_sid() which php has neither validated nor read yet
     *
     * @var string
     */
    protected $_createdId;

    /**
     * @param Zend_Session_SaveHandler_Interface $saveHandler
     */
    public function __construct(Zend_Session_SaveHandler_Interface $saveHandler)
    {
        $this->_saveHandler = $saveHandler;
    }

    /**
     * @return Zend_Session_SaveHandler_Interface
     */
    public function getSaveHandler()
    {
        return $this->_saveHandler;
    }

    /**
     * @param string $save_path
     * @param string $name
     * @return mixed return value of the wrapped save handler
     */
    #[\ReturnTypeWillChange]
    public function open($save_path, $name)
    {
        return $this->_saveHandler->open($save_path, $name);
    }

    /**
     * @return mixed return value of the wrapped save handler
     */
    #[\ReturnTypeWillChange]
    public function close()
    {
        return $this->_saveHandler->close();
    }

    /**
     * @param string $id
     * @return mixed return value of the wrapped save handler
     */
    #[\ReturnTypeWillChange]
    public function read($id)
    {
        if ($id === $this->_createdId) {
            // php started to use the generated id
            $this->_createdId = null;
        }

        return $this->_saveHandler->read($id);
    }

    /**
     * @param string $id
     * @param string $data
     * @return mixed return value of the wrapped save handler
     */
    #[\ReturnTypeWillChange]
    public function write($id, $data)
    {
        return $this->_saveHandler->write($id, $data);
    }

    /**
     * @param string $id
     * @return mixed return value of the wrapped save handler
     */
    #[\ReturnTypeWillChange]
    public function destroy($id)
    {
        return $this->_saveHandler->destroy($id);
    }

    /**
     * @param int $maxlifetime
     * @return mixed return value of the wrapped save handler
     */
    #[\ReturnTypeWillChange]
    public function gc($maxlifetime)
    {
        return $this->_saveHandler->gc($maxlifetime);
    }

    /**
     * Create a session id with php's default session id generator
     *
     * @return string
     */
    #[\ReturnTypeWillChange]
    public function create_sid()
    {
        // called from within the save handler, session_create_id() uses php's default generator
        $this->_createdId = session_create_id();

        return $this->_createdId;
    }

    /**
     * Report every session id as an existing one, except one just generated by create_sid()
     *
     * php validates incoming session ids with session.use_strict_mode enabled (accepted here, as for
     * callback save handlers), and checks session ids it just generated for collisions in
     * session_regenerate_id() and session_create_id() (reported as non-existing, so no retry happens).
     *
     * @param string $id
     * @return bool
     */
    #[\ReturnTypeWillChange]
    public function validateId($id)
    {
        if ($id === $this->_createdId) {
            $this->_createdId = null;
            return false;
        }

        return true;
    }
}
